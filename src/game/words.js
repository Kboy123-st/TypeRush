export const WORDS_BY_DIFFICULTY = {
  easy: EASY_WORDS,
  medium: MEDIUM_WORDS,
  hard: HARD_WORDS
};

/**
 * Returns a flat array of { word, difficulty } objects matching the filter.
 * @param {'all' | 'easy' | 'medium' | 'hard'} difficultyFilter
 */
export function getWordPool(difficultyFilter = 'all') {
  const filter = (difficultyFilter || 'all').toLowerCase();
  if (filter === 'easy' || filter === 'medium' || filter === 'hard') {
    return WORDS_BY_DIFFICULTY[filter].map((word) => ({
      word,
      difficulty: filter
    }));
  }

  return [
    ...WORDS_BY_DIFFICULTY.easy.map((word) => ({ word, difficulty: 'easy' })),
    ...WORDS_BY_DIFFICULTY.medium.map((word) => ({ word, difficulty: 'medium' })),
    ...WORDS_BY_DIFFICULTY.hard.map((word) => ({ word, difficulty: 'hard' }))
  ];
}

/**
 * Picks a random word entry ({ word, difficulty }) avoiding immediate repetition.
 * @param {string} previousWord
 * @param {'all' | 'easy' | 'medium' | 'hard'} difficultyFilter
 * @param {() => number} rng
 */
export function getRandomWord(previousWord = '', difficultyFilter = 'all', rng = Math.random) {
  const pool = getWordPool(difficultyFilter);
  if (pool.length === 0) {
    return { word: 'arcade', difficulty: 'medium' };
  }
  const filtered = previousWord ? pool.filter((item) => item.word !== previousWord) : pool;
  const activePool = filtered.length > 0 ? filtered : pool;
  const index = Math.min(activePool.length - 1, Math.max(0, Math.floor(rng() * activePool.length)));
  return activePool[index];
}

/**
 * Generates an ordered sequence of words for shared 1v1 multiplayer matches
 * so both players receive the exact same words in the exact same order.
 * @param {number} count
 * @param {'all' | 'easy' | 'medium' | 'hard'} difficultyFilter
 * @param {() => number} rng
 */
export function generateWordSequence(count = 120, difficultyFilter = 'all', rng = Math.random) {
  const sequence = [];
  let prev = '';
  const targetCount = Math.max(1, count);
  for (let i = 0; i < targetCount; i++) {
    const next = getRandomWord(prev, difficultyFilter, rng);
    sequence.push(next);
    prev = next.word;
  }
  return sequence;
}

